export function normalizeLabel(value: string) {
  return value
    .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
    .replace(/[_-]+/g, " ")
    .trim()
    .toLowerCase();
}

export function localizeStatus(value: unknown, lang: Lang) {
  const status = String(value ?? "—");
  const known = recordStatuses.find(
    (item) => normalizeLabel(item.value) === normalizeLabel(status),
  );
  return known ? words[lang][known.translation] : status;
}

export function localizeActivityTitle(value: string, lang: Lang) {
  const actions: Record<string, keyof typeof words.ar> = {
    LOGIN: "loginAction",
    CREATE: "createAction",
    UPDATE: "updateAction",
    DELETE: "deleteAction",
    STATUS_CHANGE: "statusChangeAction",
  };
  return words[lang][actions[value.toUpperCase()]] || value;
}

export function localizeActivityDescription(
  value: string | null | undefined,
  lang: Lang,
) {
  if (lang === "en" || !value) return value || "";
  const rules: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [
      /^User (.+) logged in successfully\.$/i,
      (match) => `تم تسجيل دخول المستخدم ${match[1]} بنجاح.`,
    ],
    [
      /^Created (.+) record (.+)\.$/i,
      (match) => `تم إنشاء سجل ${match[1]} رقم ${match[2]}.`,
    ],
    [
      /^Updated (.+) record (.+)\.$/i,
      (match) => `تم تحديث سجل ${match[1]} رقم ${match[2]}.`,
    ],
    [
      /^Deleted (.+) record (.+)\.$/i,
      (match) => `تم حذف سجل ${match[1]} رقم ${match[2]}.`,
    ],
    [
      /^Changed record (.+) status to (.+)\.$/i,
      (match) =>
        `تم تغيير حالة السجل ${match[1]} إلى ${localizeStatus(match[2], "ar")}.`,
    ],
  ];
  for (const [pattern, translate] of rules) {
    const match = value.match(pattern);
    if (match) return translate(match);
  }
  return value;
}

export function localizeLookup(value: string, lang: Lang) {
  if (lang === "en") return value;
  return arabicLookupValues[value.trim().toLowerCase()] || value;
}
